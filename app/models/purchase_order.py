from sqlalchemy import Column, Integer, String, Float, DateTime, ForeignKey, Text, Enum
from sqlalchemy.orm import relationship
from datetime import datetime
import enum
from app.database import Base

class POStatus(str, enum.Enum):
    DRAFT = "DRAFT"
    PENDING_APPROVAL = "PENDING_APPROVAL"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    TRANSMITTED = "TRANSMITTED"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    PARTIALLY_FULFILLED = "PARTIALLY_FULFILLED"
    COMPLETED = "COMPLETED"
    CANCELLED = "CANCELLED"

class ApprovalTier(str, enum.Enum):
    AUTO = "AUTO"                         # < $5,000 preferred vendor
    BUYER = "BUYER"                       # $5,000 - $25,000 or price variance
    PROCUREMENT_MANAGER = "MANAGER"       # $25,000 - $100,000
    VP_OPERATIONS = "VP"                  # > $100,000 or unapproved vendor

class PurchaseOrder(Base):
    __tablename__ = "purchase_orders"

    id = Column(Integer, primary_key=True, index=True)
    po_number = Column(String(50), unique=True, index=True, nullable=False)
    supplier_id = Column(Integer, ForeignKey("suppliers.id"), nullable=False, index=True)
    status = Column(String(30), default=POStatus.DRAFT.value, index=True)
    total_amount = Column(Float, default=0.0)
    currency = Column(String(10), default="USD")

    approval_tier = Column(String(20), default=ApprovalTier.AUTO.value)
    risk_score = Column(Float, default=0.0)  # 0.0 (low) to 1.0 (critical)
    risk_reasons = Column(Text, nullable=True)  # JSON list of flags e.g. ["High value", "New supplier"]

    expected_delivery_date = Column(DateTime, nullable=True)
    actual_delivery_date = Column(DateTime, nullable=True)
    vendor_confirmation_ref = Column(String(100), nullable=True)

    notes = Column(Text, nullable=True)
    agent_generated = Column(Integer, default=1)  # 1 if generated by AI agent, 0 if manual
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # Relationships
    supplier = relationship("Supplier", back_populates="purchase_orders")
    line_items = relationship("POLineItem", back_populates="purchase_order", cascade="all, delete-orphan")
    approval_requests = relationship("ApprovalRequest", back_populates="purchase_order", cascade="all, delete-orphan")

class POLineItem(Base):
    __tablename__ = "po_line_items"

    id = Column(Integer, primary_key=True, index=True)
    po_id = Column(Integer, ForeignKey("purchase_orders.id"), nullable=False, index=True)
    sku = Column(String(50), nullable=False, index=True)
    description = Column(String(250), nullable=True)
    quantity = Column(Integer, nullable=False)
    unit_price = Column(Float, nullable=False)
    subtotal = Column(Float, nullable=False)

    purchase_order = relationship("PurchaseOrder", back_populates="line_items")
